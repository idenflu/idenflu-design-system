import { readFile, readdir, mkdir, writeFile, unlink } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";
import path from "node:path";
import assert from "node:assert/strict";
import { DOMParser, XMLSerializer } from "@xmldom/xmldom";
import { transform } from "@svgr/core";
import jsx from "@svgr/plugin-jsx";

const packageRoot = fileURLToPath(new URL("../", import.meta.url));
const sourcePath = path.resolve(packageRoot, "../icons/src/icons.svg");
const outputDir = path.join(packageRoot, "src/icons/generated");
const banner = "// Generated by npm run generate:icons. Do not edit.\n";

const componentName = (name) =>
  `${name
    .split("-")
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("")}Icon`;

function template(hasIds) {
  return ({ componentName: name, jsx: svg }, { tpl }) => {
    svg.openingElement.name.name = "SvgIcon";
    if (svg.closingElement) svg.closingElement.name.name = "SvgIcon";
    svg.openingElement.attributes.push(
      {
        type: "JSXSpreadAttribute",
        argument: { type: "Identifier", name: "props" },
      },
      {
        type: "JSXAttribute",
        name: { type: "JSXIdentifier", name: "ref" },
        value: {
          type: "JSXExpressionContainer",
          expression: { type: "Identifier", name: "ref" },
        },
      },
    );
    const body = hasIds
      ? tpl`{
    const instanceId = React.useId();
    return ${svg};
  }`
      : svg;
    return tpl`
    import * as React from "react";
    import { SvgIcon, type SvgIconProps } from "../../components/SvgIcon/SvgIcon";
    export const ${name} = /*#__PURE__*/ (() => {
      const Component = React.forwardRef<SVGSVGElement, SvgIconProps>(
        (props, ref) => ${body}
      );
      Component.displayName = "${name}";
      return Component;
    })();
  `;
  };
}

export async function generateIcons(source) {
  const document = new DOMParser({
    onError: (level, message) => {
      throw new Error(`${level}: ${message}`);
    },
  }).parseFromString(source, "image/svg+xml");
  const root = document.documentElement;
  assert.equal(root.localName, "svg", "Expected an SVG root");
  const symbols = Array.from(root.childNodes).filter(
    (node) => node.nodeType === 1,
  );
  assert(symbols.length, "Expected at least one symbol");
  const names = new Set();
  const exports = new Set();
  const files = new Map();
  for (const symbol of symbols) {
    assert.equal(
      symbol.localName,
      "symbol",
      "Only symbols are supported at the sprite root",
    );
    const name = symbol.getAttribute("id");
    assert(
      /^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/.test(name),
      `Invalid icon name: ${name}`,
    );
    assert(!names.has(name), `Duplicate icon name: ${name}`);
    names.add(name);
    const nameInCode = componentName(name);
    assert(!exports.has(nameInCode), `Component name collision: ${nameInCode}`);
    exports.add(nameInCode);
    const svg = document.createElementNS(root.namespaceURI, "svg");
    for (const attribute of Array.from(symbol.attributes)) {
      if (attribute.name !== "id")
        svg.setAttribute(attribute.name, attribute.value);
    }
    for (const child of Array.from(symbol.childNodes))
      svg.appendChild(child.cloneNode(true));
    // Instance-local IDs prevent collisions when the same drawing appears twice.
    const nodes = Array.from(svg.getElementsByTagName("*"));
    const ids = nodes
      .filter((node) => node.hasAttribute("id"))
      .map((node) => node.getAttribute("id"));
    assert.equal(
      new Set(ids).size,
      ids.length,
      `Duplicate drawing ID: ${name}`,
    );
    const replacements = {};
    for (const id of ids) replacements[id] = `{\`\${instanceId}-${id}\`}`;
    for (const node of nodes) {
      for (const attribute of Array.from(node.attributes)) {
        const value = attribute.value;
        if (attribute.localName === "href") {
          assert(
            value.startsWith("#") && ids.includes(value.slice(1)),
            `Non-local reference in ${name}: ${value}`,
          );
          replacements[value] = `{\`#\${instanceId}-${value.slice(1)}\`}`;
        }
        const references = [
          ...value.matchAll(/url\(\s*["']?#([^\s)'";]+)["']?\s*\)/g),
        ];
        if (references.length) {
          let dynamic = value;
          for (const [, id] of references) {
            assert(ids.includes(id), `Missing drawing ID in ${name}: ${id}`);
            dynamic = dynamic.replace(`#${id}`, `#\${instanceId}-${id}`);
          }
          replacements[value] = `{\`${dynamic}\`}`;
        }
      }
    }
    const code = await transform(
      new XMLSerializer().serializeToString(svg),
      {
        plugins: [jsx],
        runtimeConfig: false,
        typescript: true,
        ref: true,
        dimensions: false,
        replaceAttrValues: replacements,
        template: template(ids.length > 0),
        jsxRuntime: "classic",
      },
      { componentName: nameInCode },
    );
    files.set(`${nameInCode}.tsx`, banner + code + "\n");
  }
  const entries = [...exports].sort();
  files.set(
    "index.ts",
    banner +
      entries.map((name) => `export { ${name} } from "./${name}";`).join("\n") +
      "\n",
  );
  return files;
}

async function main() {
  const files = await generateIcons(await readFile(sourcePath, "utf8"));
  const check = process.argv.includes("--check");
  await mkdir(outputDir, { recursive: true });
  const existing = await readdir(outputDir);
  const stale = [];
  for (const [name, content] of files) {
    const filename = path.join(outputDir, name);
    const previous = await readFile(filename, "utf8").catch(() => null);
    if (previous === content) continue;
    stale.push(name);
    if (!check) await writeFile(filename, content);
  }
  for (const name of existing) {
    if (files.has(name)) continue;
    const filename = path.join(outputDir, name);
    assert(
      (await readFile(filename, "utf8")).startsWith(banner),
      `Refusing to remove non-generated file: ${name}`,
    );
    stale.push(name);
    if (!check) await unlink(filename);
  }
  if (check && stale.length)
    throw new Error(
      `Generated icons are stale: ${stale.join(", ")}. Run npm run generate:icons.`,
    );
  console.log(`${check ? "Checked" : "Generated"} ${files.size - 1} icons.`);
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href
) {
  await main();
}
